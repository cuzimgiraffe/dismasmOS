/* 1. HEAP MANUAL ENTRY */
static const char * const doc_heap_lines[] = {
    "NAME",
    "  heap - Kernel dynamic heap memory allocator diagnostics and self-test",
    "",
    "SYNOPSIS",
    "  heap",
    "  heap test",
    "",
    "DESCRIPTION",
    "  The heap command inspects and validates the kernel's freestanding dynamic",
    "  memory allocator. In dismasmOS, there is no C standard library; all dynamic",
    "  memory (malloc, free, calloc, realloc) is managed by an independent, bare-metal",
    "  allocator implemented from scratch.",
    "",
    "  Running 'heap' without arguments prints live allocation statistics.",
    "  Running 'heap test' executes an automated validation suite that stresses all",
    "  core allocator routines.",
    "",
    "ALLOCATOR ARCHITECTURE & SPECIFICATIONS",
    "  - Memory Pool Location: Dedicated 16 MiB pool starting at physical address",
    "    0x01000000 (16 MiB boundary) up to 0x01FFFFFF (32 MiB boundary).",
    "  - 16-Byte Alignment: All memory payloads returned by malloc are strictly",
    "    aligned to 16-byte boundaries, satisfying x86_64 SSE/AVX requirements.",
    "  - 48-Byte Header Structure: Each allocated or free chunk contains:",
    "      * Magic Signature (0xDEADBEEFCAFE0001): Detects heap corruption.",
    "      * Size Field: 64-bit length of usable payload.",
    "      * Allocated Flag: Distinguishes live allocations from free blocks.",
    "      * Bidirectional Pointers: 64-bit prev and next pointers.",
    "  - Bidirectional Coalescing: When a chunk is freed, it is immediately merged",
    "    with adjacent free chunks to completely eliminate external fragmentation.",
    "  - Double-Free Detection: Guard checks abort and prevent double-free bugs.",
    "",
    "OPTIONS & MODES",
    "  heap",
    "    Displays total heap size (16 MiB), currently used bytes, remaining free",
    "    KiB, number of active allocations, and starting/ending addresses.",
    "",
    "  heap test",
    "    Runs an automated 4-stage diagnostic suite:",
    "      1. malloc test: Allocates varying chunk sizes and verifies alignment.",
    "      2. calloc test: Verifies all allocated bytes are zero-initialized.",
    "      3. realloc test: Expands and shrinks buffers, verifying data preservation.",
    "      4. free & coalesce test: Frees buffers in interleaved order and validates",
    "         that total free memory matches the original unfragmented state.",
    "",
    "PRACTICAL EXAMPLES",
    "  heap",
    "    Inspects current memory heap metrics.",
    "",
    "  heap test",
    "    Executes self-test. Prints '[  OK  ] All heap allocator tests passed!'",
    "",
    "SEE ALSO",
    "  MemRep, dump, wdid"
};

