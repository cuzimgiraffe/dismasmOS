/* 5. ASM MANUAL ENTRY */
static const char * const doc_asm_lines[] = {
    "NAME",
    "  asm - Execute dynamic machine code or x86 processor instructions in RAM",
    "",
    "SYNOPSIS",
    "  asm <mnemonic>",
    "  asm <bytecode_hex>",
    "",
    "DESCRIPTION",
    "  The asm command provides an interactive runtime environment for executing",
    "  raw x86_64 machine code instructions directly in memory. It can execute",
    "  hardware processor mnemonics or arbitrary hex byte sequences in Ring 0.",
    "",
    "HOW IT WORKS UNDER THE HOOD",
    "  When hex bytecode is provided:",
    "  1. The kernel parses the input hex tokens into an executable memory buffer.",
    "  2. Validates that the sequence terminates with a return instruction (0xC3).",
    "     If missing, the kernel automatically appends 0xC3.",
    "  3. Casts the buffer address to a 64-bit C function pointer:",
    "     typedef uint64_t (*asm_func_t)(void);",
    "  4. Calls the buffer directly as executable 64-bit code.",
    "  5. Captures the RAX register returned by the function and displays it in",
    "     both hexadecimal and decimal format.",
    "",
    "BUILT-IN MNEMONICS",
    "  asm nop",
    "    Executes a single hardware No-Operation instruction (0x90).",
    "",
    "  asm cli",
    "    Disables all maskable hardware interrupts on the CPU (clears RFLAGS.IF).",
    "",
    "  asm sti",
    "    Enables maskable hardware interrupts on the CPU (sets RFLAGS.IF).",
    "",
    "  asm rdtsc",
    "    Executes the Read Time-Stamp Counter instruction. Reads the CPU clock",
    "    cycles since processor reset into EDX:EAX and displays the 64-bit tick count.",
    "",
    "  asm cpuid",
    "    Executes CPUID with EAX=0. Extracts the 12-byte processor vendor string",
    "    from EBX, EDX, and ECX (e.g. 'GenuineIntel' or 'AuthenticAMD').",
    "",
    "RAW BYTECODE EXAMPLES",
    "  asm 48 c7 c0 2a 00 00 00 c3",
    "    Executes 'mov rax, 42; ret'. Prints Return RAX: 0x0000002A (42).",
    "",
    "SAFETY WARNING",
    "  Because bytecode executes with Ring 0 supervisor privileges, executing",
    "  invalid instructions or jumping into unmapped addresses will cause a CPU fault.",
    "",
    "SEE ALSO",
    "  reg, dump, wdid"
};

